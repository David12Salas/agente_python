def centimetros_a_pulgadas(cm: float) -> float:
    return cm / 2.54


def pulgadas_a_centimetros(pulgadas: float) -> float:
    return pulgadas * 2.54


def pies_a_metros(pies: float) -> float:
    return pies * 0.3048


def metros_a_pies(metros: float) -> float:
    return metros / 0.3048


def millas_a_km(millas: float) -> float:
    return millas * 1.60934


def km_a_millas(km: float) -> float:
    return km / 1.60934


def galones_a_litros(galones: float) -> float:
    return galones * 3.78541


def litros_a_galones(litros: float) -> float:
    return litros / 3.78541


def libras_a_kg(libras: float) -> float:
    return libras * 0.453592


def kg_a_libras(kg: float) -> float:
    return kg / 0.453592